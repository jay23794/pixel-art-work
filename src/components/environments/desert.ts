// Desert Lab's night desert: sky, mesas, sand, the camp (trailer, generator,
// string lights, smoke) and the foreground dunes. Component ids are fixed, so
// each component keeps its own random stream (and the v1 golden frames).

/** A constant level or a scene signal "@name" (checked by the loader). */
const level = z.union([z.number(), z.string().regex(/^@[A-Za-z][\w-]*$/, 'expected a number or a signal reference "@name"')]);

export const params = z.strictObject({
  /** Which scene signals drive the camp lights. */
  lights: z
    .strictObject({
      /** Mains: generator LED and the dust lit by the camp. */
      power: level.default('@lightsOn'),
      /** Trailer windows, the door's light pool and the smoke's warmth. */
      windows: level.default('@windowLight'),
      /** String lights on/off. */
      bulbs: level.default('@bulbsOn'),
      /** The string lights' pool on the sand. */
      bulbGlow: level.default('@bulbGlow'),
    })
    .prefault({}),
});
type Config = z.infer<typeof params>;

